#!/usr/bin/env python3
"""Write the macOS (Apple silicon, `macosa64`) build recipes from the ARM Linux
ones, so the differences stay small and visible. Run from the repo root:

    python3 Compiling_tools/macos/make_recipes.py

What changes for macOS:
- reader (C++, Apple clang): drop the GCC-only flags (-fpermissive,
  -traditional-cpp) and -march=armv8-a (clang targets arm64 already).
- starter / engine (Homebrew GCC: gfortran, gcc, g++ -- one OpenMP runtime,
  as on Linux): no -march=armv8-a, no -no-pie / -rdynamic (not for Mach-O),
  third-party libraries from the dependency prefix ($OC_MAC_DEPS: Homebrew or
  conda) instead of extlib's Linux builds, md5 from Compiling_tools/macos.
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))


def read(p):
    with open(os.path.join(ROOT, p), encoding='utf-8') as f:
        return f.read()


def write(p, text):
    full = os.path.join(ROOT, p)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', p)


def sub(text, old, new, count=0, required=True):
    if required and old not in text:
        sys.exit(f'make_recipes: expected text not found: {old!r}')
    return text.replace(old, new) if count == 0 else text.replace(old, new, count)


HEADER = '# macOS Apple silicon (macosa64): generated by Compiling_tools/macos/make_recipes.py\n'

# --- reader -----------------------------------------------------------------
write('reader/CMake_arch/CMake_macosa64.cmake', HEADER + '''
set (compile "macosa64")
set ( lib "dylib")
set ( libp "lib")

# Boost: headers and the filesystem library from the dependency prefix
# (extlib has prebuilt Boost for Linux and Windows only). Headers and library
# come from the same Boost, so they match.
set (oc_mac_deps "$ENV{OC_MAC_DEPS}")
if (oc_mac_deps STREQUAL "")
   message (FATAL_ERROR "macosa64: set OC_MAC_DEPS to the Homebrew or conda prefix holding Boost")
endif()
set (boost_include "${oc_mac_deps}/include")
set (boost_fs_lib "${oc_mac_deps}/lib/libboost_filesystem.dylib")
''')

for mod in ['cfgio', 'cfgkernel', 'dyna2rad', 'io', 'sdi', 'solver_interface']:
    t = read(f'reader/source/{mod}/CMake_arch/CMake_linuxa64.cmake')
    for flag in [' -march=armv8-a', ' -fpermissive', ' -traditional-cpp']:
        t = t.replace(flag, '')
    write(f'reader/source/{mod}/CMake_arch/CMake_macosa64.cmake', HEADER + t)

# Boost library and headers: use the recipe's when it sets them.
t = read('reader/CMakeLists.txt')
if 'boost_fs_lib' not in t:
    t = sub(t, '''   target_link_libraries(${link_library_name}''', '''   if (NOT DEFINED boost_fs_lib)
      set (boost_fs_lib ${open_reader_root_dir}/../extlib/boost/boost_1_70_0/static/lib/${arch}/libboost_filesystem.${lib})
   endif()
   target_link_libraries(${link_library_name}''')
    t = sub(t, '''                      ${open_reader_root_dir}/../extlib/boost/boost_1_70_0/static/lib/${arch}/libboost_filesystem.${lib})''', '''                      ${boost_fs_lib})''')
    write('reader/CMakeLists.txt', t)

t = read('reader/CMake_arch/CMake_includes.cmake')
if 'boost_include' not in t:
    t = sub(t, '''list (APPEND include_dir_list ${open_reader_root_dir}/../extlib/boost/boost_1_70_0/  )''', '''if (DEFINED boost_include)
   list (APPEND include_dir_list ${boost_include} )
else()
   list (APPEND include_dir_list ${open_reader_root_dir}/../extlib/boost/boost_1_70_0/  )
endif()''')
    write('reader/CMake_arch/CMake_includes.cmake', t)

# Reader build script: the compilers can be chosen (CC / CXX), macOS listed.
t = read('reader/build_script.bash')
if 'macosa64' not in t:
    t = sub(t, '''  echo "          linuxa64 : ARM64" ''', '''  echo "          linuxa64 : ARM64"
  echo "          macosa64 : macOS Apple silicon (clang)" ''')
    t = sub(t, '''cmake -DCMAKE_CXX_COMPILER=g++ -DCMAKE_C_COMPILER=gcc -Darch=${arch}  -Dcom=${com} ..''',
            '''cmake -DCMAKE_CXX_COMPILER=${CXX:-g++} -DCMAKE_C_COMPILER=${CC:-gcc} -Darch=${arch}  -Dcom=${com} ..''')
    write('reader/build_script.bash', t)

# --- starter and engine -----------------------------------------------------
LIBS = {
    # Linux extlib path -> dependency prefix / our md5
    '${source_directory}/../extlib/zlib/linuxa64/include': '$ENV{OC_MAC_DEPS}/include',
    '${source_directory}/../extlib/zlib/linuxa64/lib/libz.a': '-L$ENV{OC_MAC_DEPS}/lib -lz',
    '-L${source_directory}/../extlib/md5/linuxa64/ -lmd5': '${source_directory}/../extlib/md5/macosa64/libmd5.a',
    '${source_directory}/../extlib/md5/linuxa64/libmd5.a': '${source_directory}/../extlib/md5/macosa64/libmd5.a',
    '${source_directory}/../extlib/metis/linuxa64/libmetis_linuxa64.a': '-L$ENV{OC_MAC_DEPS}/lib -lmetis',
}


def mac_recipe(t, prog):
    t = t.replace(' -march=armv8-a', '').replace('-march=armv8-a ', '')
    for old, new in LIBS.items():
        t = t.replace(old, new)
    # LAPACK / BLAS: reference builds from the prefix.
    t = re.sub(r'set \(lapack_lib "[^"]*"\)', 'set (lapack_lib "-L$ENV{OC_MAC_DEPS}/lib -L$ENV{OC_MAC_DEPS}/opt/lapack/lib -llapack -lblas")', t)
    # Reader: the open reader built next to the executables.
    t = re.sub(r'set \( reader_lib "-L\$\{source_directory\}/\.\./exec -lopen_reader_linuxa64"\)',
               'set ( reader_lib "-L${source_directory}/../exec -lopen_reader_macosa64 -Wl,-rpath,@executable_path")', t)
    t = re.sub(r'set \( reader_lib "-L\$\{source_directory\}/\.\./extlib/hm_reader/linuxa64/ -lhm_reader_linuxa64 -lapr-1" \)',
               'message (FATAL_ERROR "macosa64: build with -open_reader (no prebuilt hm_reader for macOS)")', t)
    # Mach-O: no -no-pie / -rdynamic; librt is part of libSystem.
    t = t.replace(' -rdynamic', '').replace('"-rdynamic ', '"').replace(' -no-pie', '')
    t = t.replace(' -lrt', '').replace('set (LINK "rt ', 'set (LINK "')
    if 'linuxa64' in t:
        left = sorted(set(re.findall(r'\S*linuxa64\S*', t)))
        sys.exit(f'make_recipes: {prog}: still mentions linuxa64: {left}')
    return HEADER + t


for prog in ['starter', 'engine']:
    t = read(f'{prog}/CMake_Compilers/cmake_linuxa64_gf.txt')
    write(f'{prog}/CMake_Compilers/cmake_macosa64_gf.txt', mac_recipe(t, prog))
    write(f'{prog}/CMake_Compilers/cmake_macosa64_gf_compilers.sh', HEADER + '''
# Homebrew GCC for Fortran, C and C++ (one OpenMP runtime, as on Linux).
# Override with OC_FC / OC_CC / OC_CXX.
gcc_ver=`ls ${HOMEBREW_PREFIX:-/opt/homebrew}/bin/ 2>/dev/null | grep -E '^gcc-[0-9]+$' | sed 's/gcc-//' | sort -n | tail -1`
Fortran_comp=${OC_FC:-gfortran}
C_comp=${OC_CC:-gcc-${gcc_ver}}
CXX_comp=${OC_CXX:-g++-${gcc_ver}}
CPP_comp=${CXX_comp}
''')
    p = f'{prog}/CMake_Compilers/platforms.txt'
    t = read(p)
    if 'macosa64_gf' not in t:
        line = '         -arch=macosa64_gf   (SMP executable / macOS Apple silicon - Homebrew GCC; link with -open_reader)\n'
        write(p, t.rstrip('\n') + '\n' + line)
    # Build script: on a Mac the open reader is built for macosa64.
    p = f'{prog}/build_script.sh'
    t = read(p)
    if 'macosa64' not in t:
        t = sub(t, '''if [ "`uname -m`" == "x86_64" ]
then
  built_in_arch=linux64
else
  built_in_arch=linuxa64
fi''', '''if [ "`uname -s`" == "Darwin" ]
then
  built_in_arch=macosa64
elif [ "`uname -m`" == "x86_64" ]
then
  built_in_arch=linux64
else
  built_in_arch=linuxa64
fi''', required=False)
        write(p, t)
